<p>An asset is a server or device that a system depends on.</p>

<h2>Steps</h2>
<ol>
	<li>Open <strong>Assets</strong> in the menu.</li>
	<li>Choose to add a new asset, pick the organization it belongs to and fill in the details.</li>
	<li>Save. Open the asset from the list to keep documenting it.</li>
</ol>

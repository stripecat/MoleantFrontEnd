<p>A system describes a service your organization runs, for example e-mail or a line-of-business application.</p>

<h2>Steps</h2>
<ol>
	<li>Open <strong>Systems</strong> in the menu.</li>
	<li>Choose to add a new system, pick the organization it belongs to and fill in the details.</li>
	<li>Save. Open the system from the list to keep documenting it.</li>
</ol>

<p>An organization is the top level in Discover. Systems and assets are documented under an organization.</p>

<h2>Before you start</h2>
<p>You need write access to create content. If you can only read, ask an administrator of your organization to
	<a href="/support/?a=managing-access">change your access</a>.</p>

<h2>Steps</h2>
<ol>
	<li>Open <strong>Organizations</strong> in the menu.</li>
	<li>Choose to add a new organization and fill in the details.</li>
	<li>Save. The organization appears in the list.</li>
</ol>

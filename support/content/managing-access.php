<p>Access is set per organization. A person can be allowed to read, to change content, or to administer the organization,
	and separate permissions control who may see and change stored passwords.</p>

<h2>Changing someone's access</h2>
<ol>
	<li>Open <strong>Settings</strong> in the menu.</li>
	<li>Go to the permissions section and pick the organization.</li>
	<li>Change the access for the person and save.</li>
</ol>

<div class="support-note">
	<p>Hiding a button is not what protects your data: access is checked on every request, so a change takes effect
		even if the person still has an old page open.</p>
</div>
